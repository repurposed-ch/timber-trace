// Writes supabase/seed.sql for the local database (`bun run db:reset` loads it): two users that
// sign in with an email link (caught by Mailpit) and one entry per static record in
// public/<slug>/records/. Run `bun run db:seed` after changing the static records.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { listSchemas, loadSchema, type ReadText } from "../src/schema/loader";
import { staticRecordSource } from "../src/records/source";

const pub = join(import.meta.dir, "../public");
const read: ReadText = async (path) => readFileSync(join(pub, path), "utf8");
const records = staticRecordSource(read);

const users = [
  { id: "00000000-0000-4000-8000-00000000a001", email: "admin@timber-trace.test", role: "admin" },
  { id: "00000000-0000-4000-8000-00000000a002", email: "user@timber-trace.test", role: null },
];
const owner = users[1].id;

const str = (s: string) => `'${s.replace(/'/g, "''")}'`;
const json = (v: unknown) => `${str(JSON.stringify(v))}::jsonb`;
const hex = (b: Uint8Array) => `'\\x${Buffer.from(b).toString("hex")}'::bytea`;
const uuid = (h: string) => `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;

const out = [
  "-- Generated by scripts/build-seed.ts (bun run db:seed); local development only.",
  "-- Sign in with one of these addresses; the link arrives in Mailpit, http://127.0.0.1:54324.",
  "",
];

for (const u of users) {
  const app = { provider: "email", providers: ["email"], ...(u.role ? { role: u.role } : {}) };
  out.push(
    "insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at, raw_app_meta_data, raw_user_meta_data,",
    "  created_at, updated_at, confirmation_token, recovery_token, email_change_token_new, email_change)",
    `values ('00000000-0000-0000-0000-000000000000', ${str(u.id)}, 'authenticated', 'authenticated', ${str(u.email)}, '', now(), ${json(app)}, '{}',`,
    "  now(), now(), '', '', '', '');",
    "insert into auth.identities (id, user_id, provider_id, provider, identity_data, last_sign_in_at, created_at, updated_at)",
    `values (${str(u.id)}, ${str(u.id)}, ${str(u.id)}, 'email', ${json({ sub: u.id, email: u.email, email_verified: true })}, now(), now(), now());`,
    "",
  );
}

let n = 0;
for (const slug of await listSchemas(read)) {
  const schema = await loadSchema(slug, read);
  let files: string[] = [];
  try {
    files = readdirSync(join(pub, slug, "records")).filter((f) => /^[0-9a-f]{32}\.json$/.test(f)).sort();
  } catch {
    continue; // a schema without static records
  }
  for (const file of files) {
    const [e] = await records.latest(schema, uuid(file.slice(0, 32)), null);
    if (!e) throw new Error(`${slug}/records/${file} does not decode`);
    const id = `00000000-0000-4000-8000-${(++n).toString(16).padStart(12, "0")}`;
    out.push(
      "insert into public.entries (id, schema, component_id, revision, payload, history, created_by, created_at)",
      `values (${str(id)}, ${str(slug)}, ${str(e.componentId)}, ${e.revision ?? "null"}, ${hex(e.payload)}, ${e.history ? json(e.history) : "null"},`,
      `  ${str(owner)}, ${e.savedAt ? `${str(e.savedAt)}::timestamptz` : "now()"});`,
    );
  }
}

writeFileSync(join(import.meta.dir, "../supabase/seed.sql"), out.join("\n") + "\n");
console.log(`seed.sql: ${users.length} users, ${n} entries`);
